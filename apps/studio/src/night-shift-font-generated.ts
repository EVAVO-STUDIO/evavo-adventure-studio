for (const letter of "abcdefghijklmnopqrstuvwxyz") {
  G[letter] = G[letter.toUpperCase()]!;
}

const glyphForCodePoint = (codePoint: number): readonly string[] => G[String.fromCodePoint(codePoint)] ?? G["?"]!;

const FONT_WIDTH = 96;
const FONT_HEIGHT = 48;
const CELL_WIDTH = 6;
const CELL_HEIGHT = 8;
const FIRST_CODE_POINT = 33;
const GLYPH_COUNT = 94;

export const nightShiftFontIndexBytes = (): Uint8Array => {
  const indices = new Uint8Array(FONT_WIDTH * FONT_HEIGHT);
  for (let glyphIndex = 0; glyphIndex < GLYPH_COUNT; glyphIndex += 1) {
    const codePoint = FIRST_CODE_POINT + glyphIndex;
    const pattern = glyphForCodePoint(codePoint);
    const cellX = (glyphIndex % 16) * CELL_WIDTH;
    const cellY = Math.floor(glyphIndex / 16) * CELL_HEIGHT;
    for (let y = 0; y < 7; y += 1) {
      const row = pattern[y]!;
      for (let x = 0; x < 5; x += 1) {
        if (row[x] === "#") indices[(cellY + y) * FONT_WIDTH + cellX + x] = 1;
      }
    }
  }
  return indices;
};

const fontRgba = (): Uint8Array => {
  const indices = nightShiftFontIndexBytes();
  const rgba = new Uint8Array(indices.length * 4);
  for (let index = 0; index < indices.length; index += 1) {
    const offset = index * 4;
    if (indices[index] === 0) {
      rgba[offset] = 0;
      rgba[offset + 1] = 0;
      rgba[offset + 2] = 0;
      rgba[offset + 3] = 0;
    } else {
      rgba[offset] = 227;
      rgba[offset + 1] = 223;
      rgba[offset + 2] = 214;
      rgba[offset + 3] = 255;
    }
  }
  return rgba;
};

export const nightShiftFontPngBytes = (): Uint8Array =>
  encodeNativeRgbaPng(FONT_WIDTH, FONT_HEIGHT, fontRgba());

