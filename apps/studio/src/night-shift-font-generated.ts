const glyph = (...rows: readonly string[]): readonly string[] => {
  if (rows.length !== 7 || rows.some((row) => row.length !== 5 || /[^.#]/u.test(row))) {
    throw new RangeError("Night Shift 5×7 glyphs require seven rows of five '.'/'#' pixels.");
  }
  return rows;
};

